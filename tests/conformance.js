// The same SDK contract runs in native Node.js and in each isolated k6 VU.
export async function conformance(createClient, namespace, password, verify) {
  const a = createClient();
  const b = createClient();
  const anonymous = createClient();
  const clients = [a, b];
  async function rejected(operation, statuses, label) {
    let status;
    try { await operation(); } catch (error) { status = error.status; }
    verify(statuses.includes(status), `${label} (HTTP ${status ?? 'none'})`);
  }
  const forbidden = (operation, label) => rejected(operation, [403, 404], label);
  try {
    for (const [index, client] of clients.entries()) {
      const username = `${namespace}${index}`;
      await client.register({ username, password });
      await client.login(username, password);
      verify(client.user()?.username === username, 'registered account can log in');
    }
    const authorA = a.user().id;
    const authorB = b.user().id;
    verify(authorA !== authorB, 'clients have distinct identities');
    verify(a.tokens().auth_token !== b.tokens().auth_token, 'clients have isolated auth tokens');
    const postsA = a.records('posts');
    const postsB = b.records('posts');
    const postA = await postsA.create({ author: authorA, title: 'A post', body: 'a'.repeat(1024) });
    const postB = await postsB.create({ author: authorB, title: 'B post', body: 'b'.repeat(1024) });
    const original = await postsA.read(postA);
    verify(original.body.length === 1024 && original.author === authorA, 'create/read preserves body and owner');
    verify(Number.isInteger(original.created_at) && Number.isInteger(original.updated_at), 'timestamps generated by service');
    verify((await anonymous.records('posts').read(postA)).title === 'A post', 'anonymous public read works');
    const feed = await postsA.list({ pagination: { limit: 20 }, order: ['-created_at', '-id'] });
    verify(feed.records.length > 0 && feed.records.length <= 20, 'public feed returns a bounded nonempty page');
    verify(feed.records.some(post => post.id === postA), 'public feed includes created post');
    verify(!('total_count' in feed), 'feed does not request total counts');
    verify(feed.records.every(post => !('email' in post) && !('password' in post)), 'feed exposes no auth fields');
    const own = await postsA.list({ pagination: { limit: 20 }, order: ['-created_at', '-id'], filters: [{ column: 'author', value: authorA }] });
    verify(own.records.some(post => post.id === postA) && own.records.every(post => post.author === authorA), 'own posts filtered server-side');
    for (let index = 0; index < 22; index++) {
      await postsA.create({ author: authorA, title: `Pagination ${index}`, body: 'p'.repeat(1024) });
    }
    const latest = await postsA.list({ pagination: { limit: 20 }, order: ['-created_at', '-id'] });
    verify(latest.records.length === 20, 'feed page limit enforced with more than 20 posts');
    const binaryId = id => atob(id.replaceAll('-', '+').replaceAll('_', '/'));
    verify(latest.records.every((post, index, rows) => index === 0 ||
      rows[index - 1].created_at > post.created_at ||
      (rows[index - 1].created_at === post.created_at && binaryId(rows[index - 1].id) > binaryId(post.id))), 'feed ordered by descending timestamp and native ID');
    const ownPage = await postsA.list({ pagination: { limit: 20 }, order: ['-created_at', '-id'], filters: [{ column: 'author', value: authorA }] });
    verify(ownPage.records.length === 20 && ownPage.records.every(post => post.author === authorA), 'own-feed pagination and filtering compose correctly');

    await forbidden(() => postsA.create({ author: authorB, title: 'spoof', body: 'bad' }), 'cannot spoof post owner');
    await forbidden(() => postsA.create({ author: authorA, title: 'backdated', body: 'bad', created_at: 1 }), 'cannot supply creation timestamp');
    await forbidden(() => postsB.update(postA, { body: 'hijack' }), 'cannot edit another user post');
    await forbidden(() => postsB.delete(postA), 'cannot delete another user post');
    for (const fields of [{ author: authorB }, { author: null }, { created_at: 1 }, { updated_at: 1 }]) {
      await forbidden(() => postsA.update(postA, fields), `cannot alter protected post field: ${Object.keys(fields)[0]}`);
    }
    // TrailBase validates mismatched primary keys before evaluating ACLs.
    await rejected(() => postsA.update(postA, { id: postB }), [400], 'cannot change post primary key');
    const unchanged = await postsA.read(postA);
    verify(JSON.stringify(unchanged) === JSON.stringify(original), 'rejected mutations leave post unchanged');
    await postsA.update(postA, { title: 'Edited', body: 'edited body' });
    const edited = await postsA.read(postA);
    verify(edited.title === 'Edited' && edited.body === 'edited body', 'edit own post persists');
    verify(edited.author === authorA && edited.created_at === original.created_at && edited.updated_at >= original.updated_at, 'edit preserves owner and creation time');

    const likesA = a.records('likes');
    const likesB = b.records('likes');
    const like = await likesA.create({ user: authorA, post: postB });
    verify((await likesA.read(like)).post === postB, 'like persists for the correct post');
    verify((await likesA.list()).records.some(row => row.id === like), 'own-like list contains own like');
    await forbidden(() => likesB.read(like), 'cannot read another user like');
    verify((await likesB.list()).records.every(row => row.user === authorB), 'own-like list cannot expose another user likes');
    await forbidden(() => likesB.delete(like), 'cannot remove another user like');
    await forbidden(() => likesA.create({ user: authorB, post: postA }), 'cannot spoof like owner');
    await rejected(() => likesA.create({ user: authorA, post: postB }), [400, 409], 'duplicate like rejected');
    await likesA.delete(like);
    await rejected(() => likesA.read(like), [403, 404], 'removed like is no longer readable');
    verify((await likesA.list({ filters: [{ column: 'id', value: like }] })).records.length === 0, 'unlike actually removes existing like');
    await postsB.delete(postB);
    await rejected(() => likesA.create({ user: authorA, post: postB }), [400, 409], 'nonexistent post reference rejected');
    await forbidden(() => anonymous.records('posts').create({ author: authorA, title: 'bad', body: 'bad' }), 'anonymous writes rejected');
    await forbidden(() => anonymous.records('likes').list(), 'anonymous own-like reads rejected');

    verify(await a.refreshAuthToken({ force: true }), 'SDK token refresh reaches server');
    verify((await postsA.read(postA)).author === authorA, 'refreshed session remains usable');
    const refreshToken = a.tokens().refresh_token;
    await a.logout();
    verify(a.user() === undefined, 'logout clears local identity');
    await rejected(() => a.fetch('/api/auth/v1/refresh', { method: 'POST', body: JSON.stringify({ refresh_token: refreshToken }) }), [401], 'logout revokes refresh token on server');
    await forbidden(() => postsA.create({ author: authorA, title: 'bad', body: 'bad' }), 'logged-out client cannot write');
    await a.login(`${namespace}0`, password);
    verify(a.user().id === authorA, 'account can log in after logout');
  } finally {
    // Only freshly created test accounts; native deletion cascades their test data.
    for (const client of clients) {
      if (client.user()) await client.deleteUser();
    }
  }
}
